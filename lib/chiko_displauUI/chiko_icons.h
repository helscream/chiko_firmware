const uint8_t* pickBatteryIcon(uint8_t pct,bool isCharging) {
  if (pct >= 95 && isCharging) return icon_battery_100_charging;
  if (pct >= 75 && isCharging) return icon_battery_75_charging;
  if (pct >= 50 && isCharging) return icon_battery_50_charging;
  if (pct >= 25 && isCharging) return icon_battery_25_charging;
  if (pct >= 0 && isCharging) return icon_battery_0_charging;

  if (pct >= 95 && !isCharging) return icon_battery_100;
  if (pct >= 75 && !isCharging) return icon_battery_75;
  if (pct >= 50 && !isCharging) return icon_battery_50;
  if (pct >= 25 && !isCharging) return icon_battery_25;
  return icon_battery_0;
}


